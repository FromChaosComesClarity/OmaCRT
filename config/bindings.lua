-- OmaCRT: F13/F14 are unmapped on any real keyboard -- the gamepad daemon
-- (daemon/omacrt_input.py) uses them as a synthetic-only control channel,
-- Guide button -> F13, Select button -> F14. Not meant to be pressed on an
-- actual keyboard, though nothing stops it.
o.bind("F13", "OmaCRT: toggle launcher", "omarchy-shell shell toggle org.omacrt.launcher '{}'")
o.bind("F14", "OmaCRT: toggle controller cheatsheet", "omarchy-shell shell toggle org.omacrt.cheatsheet '{}'")
